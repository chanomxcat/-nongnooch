// tokens.json + icons/*.svg -> generated/tokens.css, generated/icons.svg, generated/icon-names.ts
// Plain Node (no Style Dictionary). Dart output is deferred (demo slice).
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const out = join(root, 'generated');

/** Flatten nested tokens to [["color-brand-primary", value, node], ...]. */
export function flatten(obj, prefix = []) {
  const rows = [];
  for (const [k, v] of Object.entries(obj)) {
    if (v && typeof v === 'object' && '$value' in v) rows.push([[...prefix, k].join('-'), v.$value, v]);
    else if (v && typeof v === 'object') rows.push(...flatten(v, [...prefix, k]));
  }
  return rows;
}

export function buildCss(tokens) {
  const lines = [];
  for (const [name, value, node] of flatten(tokens)) {
    lines.push(`  --${name}: ${value};`);
    if (name.startsWith('type-')) {
      lines.push(`  --${name}-lh: ${node.lineHeight};`);
      lines.push(`  --${name}-weight: ${node.weight};`);
    }
  }
  return `/* generated by packages/tokens/build.mjs, do not edit */
:root {
${lines.join('\n')}
}
html:lang(zh-Hans) body, html:lang(ja) body, html:lang(ko) body { line-height: 1.6; }
html:lang(de) :is(h1, h2, h3, h4, h5, h6, .nn-btn) { hyphens: auto; overflow-wrap: anywhere; }
`;
}

/** Convert one Figma-exported SVG into a themeable <symbol>. */
export function toSymbol(name, svg) {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? '0 0 24 24';
  let inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  inner = inner
    .replace(/<defs>[\s\S]*?<\/defs>/g, '')
    .replace(/\s(id|clip-path)="[^"]*"/g, '')
    .replace(/(stroke|fill)="(#[0-9A-Fa-f]{3,8}|white|black)"/g, '$1="currentColor"')
    .replace(/\s+/g, ' ')
    .trim();
  return `<symbol id="${name}" viewBox="${viewBox}" fill="none">${inner}</symbol>`;
}

export function buildSprite(dir) {
  const files = readdirSync(dir).filter((f) => f.endsWith('.svg')).sort();
  const names = files.map((f) => f.replace(/\.svg$/, ''));
  const symbols = files.map((f, i) => toSymbol(names[i], readFileSync(join(dir, f), 'utf8')));
  return {
    names,
    sprite: `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${symbols.join('')}</svg>\n`,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(out, { recursive: true });
  const tokens = JSON.parse(readFileSync(join(root, 'tokens.json'), 'utf8'));
  writeFileSync(join(out, 'tokens.css'), buildCss(tokens));
  const { names, sprite } = buildSprite(join(root, 'icons'));
  writeFileSync(join(out, 'icons.svg'), sprite);
  writeFileSync(
    join(out, 'icon-names.ts'),
    `// generated by packages/tokens/build.mjs\nexport const iconNames = ${JSON.stringify(names)} as const;\nexport type IconName = (typeof iconNames)[number];\n`,
  );
  console.log(`tokens: ${flatten(tokens).length} vars, ${names.length} icons`);
}
